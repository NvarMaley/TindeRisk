const test=require("node:test"),assert=require("node:assert/strict"),fs=require("node:fs"),vm=require("node:vm"),path=require("node:path");
const source=fs.readFileSync(path.resolve(__dirname,"../../apps/web/app.js"),"utf8");
test("client navigation keeps technical research separate; mandate exposes objective selection",()=>{
  const html=fs.readFileSync(path.resolve(__dirname,"../../apps/web/index.html"),"utf8");
  const form=fs.readFileSync(path.resolve(__dirname,"../../apps/web/mandate.js"),"utf8");
  assert.match(html,/<nav class="client-nav"/);
  assert.match(html,/<details class="research-nav"/);
  assert.match(form,/class="goal-picker"/);
  assert.match(form,/length:11/);
  assert.match(form,/select\("currency",\["USD","CHF"\]\)/);
  assert.match(form,/form\.insertBefore\(goalPanel/);
  const mandate=html.match(/<section id="mandate"[\s\S]*?<\/section>/)[0];
  assert.doesNotMatch(mandate,/objectives-panel/);
});

